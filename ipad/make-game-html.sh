#!/bin/sh
# Rebuilds ChariotsOfGrace.swiftpm/GameHTML.swift from the web game, so the iPad/iPhone app
# carries the whole game inside it (one HTML page with the CSS and JavaScript inlined).
# Run from anywhere after changing the game:  sh ipad/make-game-html.sh
set -e
GAME="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$GAME/ipad/ChariotsOfGrace.swiftpm/GameHTML.swift"
{
  echo '// Generated by ipad/make-game-html.sh from the web game. Do not edit by hand.'
  echo 'let gameHTML = #"""'
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      *'rel="manifest"'*|*'rel="icon"'*|*'rel="apple-touch-icon"'*) ;;
      *'href="css/style.css"'*) echo '<style>'; cat "$GAME/css/style.css"; echo '</style>' ;;
      *'<script src="js/'*)
        f=$(printf '%s' "$line" | sed 's/.*src="\([^"]*\)".*/\1/')
        echo '<script>'; cat "$GAME/$f"; echo '</script>' ;;
      *) printf '%s\n' "$line" ;;
    esac
  done < "$GAME/index.html"
  echo '"""#'
} > "$OUT"
echo "Wrote $OUT"
